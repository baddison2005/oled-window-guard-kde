"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("packages/kwin-script/contents/ui/main.qml","utf8");
const helpers=source.slice(source.indexOf("    function read("),source.indexOf("    function outputsNow("));
const first={name:"LG"},second={name:"HDMI"},a={id:"desktop-a"},b={id:"desktop-b"};
const current=new Map([[first,a],[second,b]]);
const context={Workspace:{currentDesktop:a,currentDesktopForScreen:output=>current.get(output)},sessionEpoch:"test"};
vm.createContext(context);vm.runInContext(helpers,context);
const window=(output,desktop)=>({output,desktops:[desktop],onAllDesktops:false});
assert.equal(context.desktopMembership(window(first,a)),true);
assert.equal(context.desktopMembership(window(second,b)),true,"visible HDMI window must not use LG's desktop");
context.Workspace.currentDesktop=b;
assert.equal(context.desktopMembership(window(first,a)),true,"changing active screen must not hide LG candidates");
assert.equal(context.desktopMembership(window(second,a)),false,"inactive HDMI desktop stays excluded");
assert.equal(context.desktopMembership(window(first,b)),false,"inactive LG desktop stays excluded");
assert.equal(context.desktopMembership({...window(null,a),onAllDesktops:true}),true);
assert.equal(context.desktopMembership(window(null,a)),null);
current.set(second,null);assert.equal(context.desktopMembership(window(second,b)),null);
context.Workspace.currentDesktopForScreen=()=>{throw Error("unavailable")};
assert.equal(context.desktopMembership(window(first,a)),null,"query failure must not fall back to active-screen desktop");
console.log("per-output desktop membership: 9 visibility and fail-closed cases passed");
